struct Injected {
    draw: Option<u32>,
    total_seen: Option<f32>,
}

impl WeightedDraw for Injected {
    fn draw_weight(&mut self, total: f32) -> f32 {
        assert!(self.total_seen.is_none(), "exactly one weighted draw per lottery");
        self.total_seen = Some(total);
        self.draw.map_or(total, f32::from_bits)
    }
}

#[test]
fn net_random_matches_the_game_generator() {
    assert!(RANDOM_NEXT_BELOW.len() > 10 && RANDOM_NEXT_SEQUENCE.len() > 10);
    for &(seed, n, want) in RANDOM_NEXT_BELOW {
        assert_eq!(NetRandom::new(seed).next_below(n), want, "seed {seed} Next({n})");
    }
    let mut distinct = std::collections::HashSet::new();
    for &(seed, step, want) in RANDOM_NEXT_SEQUENCE {
        let mut random = NetRandom::new(seed);
        let got = (0..=step).map(|_| random.next()).last().unwrap();
        assert_eq!(got, want, "seed {seed} Next() step {step}");
        distinct.insert(want);
    }
    assert!(distinct.len() > 20, "the compared values are not constant");
}

#[test]
fn member_count_lottery_matches_the_game_lottery() {
    let mut results = std::collections::HashSet::new();
    for &(set, counts, draw, sum_bits, want) in MEMBER_COUNT_CASES {
        let [a, b, c, d] = WEIGHT_SETS[set].map(f32::from_bits);
        let weights = LotteryWeights { talk1: a, talk2: b, talk3: c, talk4: d };
        let mut rand = Injected { draw, total_seen: None };
        let got = lottery_member_count(counts, &weights, &mut rand);
        assert_eq!(got, want, "set {set} counts {counts:?} draw {draw:?}");
        assert_eq!(rand.total_seen.map(f32::to_bits), Some(sum_bits), "set {set} counts {counts:?} sum");
        results.insert(want);
    }
    assert_eq!(results.len(), 5, "results 0..=4 all occur");
}
