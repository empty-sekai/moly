export function weatherUiMessages(locale) {
  return messages[locale] ?? messages["en-US"];
}
export function weatherPeriodLabel(period, locale) {
  const t = weatherUiMessages(locale);
  return t[period === "nighttime" ? "night" : period] ?? period;
}
export function weatherPhaseLabel(weather, locale) {
  const t = weatherUiMessages(locale),
    transition = weather?.transition;
  const phase = transition?.phase ?? "ready";
  if (phase === "ready") return t.current;
  if (phase === "waiting") return t.waiting;
  const target =
    weather.options.find((o) => o.id === transition?.requestedId)?.label ?? "";
  return `${phase === "transitioning" ? t.pending : t.loading}${target ? ` · ${target}` : ""}`;
}
